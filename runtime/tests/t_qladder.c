// 档位梯子判定单测（runtime/src/qladder.c）：喂时间序列，期望按规则手算——
//   两档 0 = 60 帧、1 = 30 帧；窗口 = 局内画面 30 秒；降档：慢帧（> 目标 × 1.5）> 5% 或中位 > 目标 × 1.05；热状态不参与；没有 GPU 读数不降不升；
//   升档：GPU 占比 × 2 < 70% 攒满 2 分钟、离上次换档 ≥ 5 分钟；60 帧档 GPU < 70% 还降 = CPU 跟不上，本局不按余量升回；再试 60 帧回 0 档、清记号
#include "s2a_qladder.h"
#include <stdio.h>
static int bad;
#define CHECK(c, ...) do { if (!(c)) { printf("✗ " __VA_ARGS__); printf("\n"); bad++; } else { printf("✓ " __VA_ARGS__); printf("\n"); } } while (0)
static double T, G; static int HIT;   // 当前时刻（秒）、GPU 忙累计（毫秒）、feed 喂的帧是不是首遇现编 / 首传贴图（hitch；现有各项都喂 0）
// 喂 sec 秒、每帧 ms 毫秒；game 局内画面；gpu GPU 忙占比（< 0 = 没有读数，喂 -1）；th 热状态；itv 游戏自设间隔。返回第一次换到的档（-1 没换），*at 换档时刻
static int feed(double sec, double ms, int game, double gpu, int th, int itv, double *at) {
    int got = -1;
    for (double end = T + sec; T < end - 1e-9; ) { T += ms / 1000; if (gpu >= 0) G += ms * gpu;
        int r = s2a_ql_frame((uint64_t)(T * 1e9), game, (uint64_t)(ms * 1e6), gpu >= 0 ? G : -1, th, itv, HIT);
        if (r >= 0 && got < 0) { got = r; if (at) *at = T; } }
    return got;
}
// 按帧数喂（一次性卡顿两项用：按秒喂时浮点累加会让 0.3 秒有时出 4 帧，卡顿帧占比漂过 2.5% 门槛）
static int feedn(int n, double ms, double gpu, int hit) {
    int got = -1;
    for (int i = 0; i < n; i++) { T += ms / 1000; G += ms * gpu; int r = s2a_ql_frame((uint64_t)(T * 1e9), 1, (uint64_t)(ms * 1e6), G, 0, 1, hit); if (r >= 0 && got < 0) got = r; }
    return got;
}
static void fresh(void) { s2a_ql_setup(); T = 1000; G = 0; }
int main(void) {
    double at = 0, t0; int r;
    T = 1000; CHECK(feed(60, 50, 1, 0.9, 0, 1, 0) < 0, "没开局（没 setup）：不判");
    fresh();
    CHECK(s2a_ql_tier() == 0 && s2a_ql_fps60(0) && !s2a_ql_fps60(1), "开局 60 帧档；两档：0 放开 60 帧、1 压回 30 帧");
    CHECK(feed(120, 16.667, 1, 0.5, 0, 1, 0) < 0, "60 帧档稳 60 帧 2 分钟：不换档");
    fresh(); r = feed(40, 33.333, 1, 0.9, 0, 1, &at);
    CHECK(r == 1 && s2a_ql_why() == S2A_QL_WHY_FPS && at - 1000 > 29.9 && at - 1000 < 30.1, "60 帧档只跑出 30 帧：满一个窗口（30 秒）那一刻压回 30 帧（实 档 %d，第 %.2f 秒）", r, at - 1000);
    // 每 30 帧里 1 帧 33.3 ms（3.3% 慢帧）、中位 16.7：不降；每 10 帧 1 帧慢（10%）：降
    fresh(); r = -1; for (int i = 0; i < 100 && r < 0; i++) { r = feed(0.4833, 16.667, 1, 0.5, 0, 1, 0); if (r < 0) r = feed(0.0333, 33.333, 1, 0.5, 0, 1, 0); }
    CHECK(r < 0, "慢帧约 3.3%%（每 29 帧 16.7 ms 夹 1 帧 33.3 ms）：不降（实 %d）", r);
    fresh(); r = -1; for (int i = 0; i < 200 && r < 0; i++) { r = feed(0.15, 16.667, 1, 0.5, 0, 1, 0); if (r < 0) r = feed(0.0333, 33.333, 1, 0.5, 0, 1, 0); }
    CHECK(r == 1, "慢帧约 10%%（每 9 帧夹 1 帧 33.3 ms）：压回 30 帧（实 %d）", r);
    fresh(); CHECK(feed(120, 16.667, 1, 0.5, 3, 1, 0) < 0, "热状态 3（危急）、帧率跟得上 2 分钟：不降（热状态不参与）");
    // #1688 没有 GPU 读数：判不了是不是 GPU 跟不上，照玩家选的 60 帧跑——只跑出 30 帧 10 分钟也不降；对照：同样喂数有读数 30 秒就降（上面第 3 项）
    fresh(); r = feed(600, 33.333, 1, -1, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 0, "没有 GPU 读数、60 帧档只跑出 30 帧 10 分钟：不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    // 升档：降档那一窗 GPU 80%（GPU 是瓶颈，不算 CPU 跟不上）；之后 30 帧跟得上、GPU 20%（× 2 = 40% < 70%）：
    //   余量 2 分钟早攒够，离换档 5 分钟那个窗口升（每窗 901 帧 × 33.333 ms = 30.033 秒，第 10 窗 300.33 秒）
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, &at); t0 = at; CHECK(s2a_ql_tier() == 1 && !s2a_ql_cpu_bound(), "60 帧档 GPU 80%% 降档：压回 30 帧、不算 CPU 跟不上");
    r = feed(320, 33.333, 1, 0.2, 0, 1, &at); CHECK(r == 0 && s2a_ql_why() == S2A_QL_WHY_UP && at - t0 > 299 && at - t0 < 301, "30 帧档余量足：离换档 5 分钟那个窗口升回 60 帧（实 %d，换档后 %.1f 秒）", r, at - t0);
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); CHECK(feed(600, 33.333, 1, 0.4, 0, 1, 0) < 0, "30 帧档 GPU 40%%（× 2 = 80%% ≥ 70%%）：10 分钟不升");
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); CHECK(feed(600, 50, 1, 0.9, 0, 1, 0) < 0 && s2a_ql_tier() == 1, "30 帧档也跟不上（20 帧）：没处可降，不换");
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); r = feed(600, 33.333, 1, -1, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 1, "30 帧档读数没了：不升（实 %d）", r);
    fresh(); CHECK(feed(120, 33.333, 0, 0.9, 0, 1, 0) < 0, "菜单 / 加载（非局内画面）30 帧 2 分钟：不降");
    fresh(); CHECK(feed(120, 33.333, 1, 0.17, 0, 2, 0) < 0, "60 帧档、游戏自设间隔 2（标题 / 过场自己锁 30 帧）、30 帧 2 分钟：不降（游戏自己限的帧，不是跑不动）");
    fresh(); r = feed(40, 50, 1, 0.9, 0, 2, 0); CHECK(r == 1, "60 帧档、游戏自设间隔 2 但只跑出 20 帧（目标 33.3 ms）：照常降（实 %d）", r);
    // 11-26 一次性卡顿（D-CCAG）：每 3 秒 159 帧 = 150 帧 16.7 ms + 6 帧 33.3 ms（真慢）+ 3 帧 100 ms 首遇现编（hitch），GPU 30%；30 秒窗口正好 10 段。
    //   慢帧 9 / 159 = 5.7% > 5%；卡顿帧 3 / 159 = 1.9% ≤ 2.5% → 扣掉，慢帧 6 / 159 = 3.8% → 2 分钟不降。旧：不分卡顿帧，第一个窗口满就压回 30 帧（记成 CPU 跟不上）
    fresh(); r = -1; for (int i = 0; i < 40 && r < 0; i++) { r = feedn(150, 16.667, 0.3, 0); if (r < 0) r = feedn(6, 33.333, 0.3, 0); if (r < 0) r = feedn(3, 100, 0.3, 1); }
    CHECK(r < 0 && s2a_ql_tier() == 0 && s2a_ql_last_hitch() == 30, "一次性卡顿：首遇现编帧 1.9%% 占窗口、扣掉 30 帧后慢帧 3.8%%：不降（实 换档 %d、档 %d、扣 %d）", r, s2a_ql_tier(), s2a_ql_last_hitch());
    // 【负对照开始】一直在现编：每 107 帧 = 100 帧 16.7 ms + 3 帧 33.3 ms + 4 帧 100 ms hitch → 卡顿帧 3.7% > 2.5%，照常算，慢帧 6.5% → 降
    fresh(); r = -1; for (int i = 0; i < 40 && r < 0; i++) { r = feedn(100, 16.667, 0.3, 0); if (r < 0) r = feedn(3, 33.333, 0.3, 0); if (r < 0) r = feedn(4, 100, 0.3, 1); }
    CHECK(r == 1 && s2a_ql_last_hitch() == -1, "一直在现编：卡顿帧 3.7%% > 2.5%%，照常算慢帧 → 压回 30 帧、读数记「卡顿帧太多」（实 档 %d、last_hitch %d）", r, s2a_ql_last_hitch());
    // 【负对照结束】
    // 11-25 局中游戏把自设间隔从 2 改成 1（帧率补丁局中才武装）：前 20 秒 33.3 ms（间隔 2），后 60 秒稳 16.7 ms（间隔 1）。窗口在改间隔那一帧重开 → 不降。
    //   旧：改后 10 秒窗口满，按间隔 1 的目标判，前 600 帧 33.3 ms 全是慢帧（> 25 ms），慢帧 50% → 压回 30 帧
    fresh(); feed(20, 33.333, 1, 0.17, 0, 2, 0); r = feed(60, 16.667, 1, 0.3, 0, 1, 0);
    CHECK(r < 0 && s2a_ql_tier() == 0, "游戏局中把自设间隔 2 改 1、之后稳 60 帧：窗口从改间隔那帧重攒，不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    fresh(); feed(20, 33.333, 1, 0.17, 0, 2, 0); r = feed(40, 33.333, 1, 0.9, 0, 1, &at);
    CHECK(r == 1 && at - 1020 > 29.9 && at - 1020 < 30.1, "改成间隔 1 后真只跑出 30 帧：从改间隔起满 30 秒那一刻照常降（实 档 %d，改后第 %.2f 秒）", r, at - 1020);
    // CPU 跟不上（11-17 派对游戏 iPad 60 / 30 每 5 分钟来回切）：60 帧档只跑出 48 帧、GPU 30%（< 70%）→ 降、记成 CPU 跟不上；之后 GPU 15% 跑 20 分钟也不升回
    fresh(); r = feed(30.01, 20.833, 1, 0.3, 0, 1, 0);
    CHECK(r == 1 && s2a_ql_cpu_bound(), "60 帧档 48 帧、GPU 30%%：压回 30 帧（实 档 %d）、记成 CPU 跟不上（实 %d）", r, s2a_ql_cpu_bound());
    r = feed(1200, 33.333, 1, 0.15, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 1, "CPU 跟不上压回的 30 帧、GPU 15%% 跑 20 分钟：不升回 60（实 换档 %d、档 %d）", r, s2a_ql_tier());
    // 再试 60 帧（玩家点横幅按钮 / 局中重开 60 帧）：当场回 60 帧档、原因 4；CPU 跟不上的记号清掉——再降一次（GPU 80%）后余量够照常升回
    s2a_ql_retry((uint64_t)(T * 1e9)); CHECK(s2a_ql_tier() == 0 && s2a_ql_why() == S2A_QL_WHY_RETRY && !s2a_ql_cpu_bound(), "再试 60 帧：回 60 帧档、原因 4、清 CPU 跟不上");
    CHECK(feed(120, 16.667, 1, 0.5, 0, 1, 0) < 0, "再试后跑稳 60 帧 2 分钟：不换档");
    // 11-24 #2201 玩家自选优先：点过再试，本局不再自动降——60 帧档只跑出 30 帧 10 分钟也不降、读数照记；下一局（setup）照旧从头判
    CHECK(s2a_ql_stick(), "再试后本局记为玩家要 60 帧");
    r = feed(600, 33.333, 1, 0.8, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 0, "再试后只跑出 30 帧 10 分钟：不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    { double f, s, g; int th; s2a_ql_last(&f, &s, &g, &th); CHECK(f > 29 && f < 31, "再试后不降，读数照记（最近一窗 %.1f 帧/秒）", f); }
    // #2201 玩家复现：匀速 52 帧（19.23 ms，中位 > 17.5）原先每 30 秒降一次、三分钟降 6 次；点过再试后三分钟 0 次
    fresh(); r = feed(30.01, 19.23, 1, 0.9, 0, 1, 0); CHECK(r == 1, "52 帧匀速、没点过再试：满一窗压回 30 帧（原判据不变，实 %d）", r);
    s2a_ql_retry((uint64_t)(T * 1e9)); r = feed(180, 19.23, 1, 0.9, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 0, "52 帧匀速、点过再试：三分钟不再降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    fresh(); CHECK(!s2a_ql_stick(), "下一局（setup）清掉本局的再试记号");
    // #1949 不在前台的时段不算：60 帧档稳 60 帧 20 秒 → 失焦 40 秒（系统降速，宿主每帧调 s2a_ql_away、不喂帧）→ 回前台头 3 秒慢帧（20 帧，带后台余波）→ 稳 60 帧 60 秒：
    //   不降（期望：后台 40 秒与回前台 3 秒都不进窗口，窗口从回前台第 3 秒起只有 60 帧，判不降）。
    //   对照（负控）：同一序列不调 s2a_ql_away、把后台那段当局内帧喂进去（20 帧）→ 第一个 30 秒窗口里慢帧约 1/3 > 5%：压回 30 帧
    fresh(); feed(20, 16.667, 1, 0.11, 0, 1, 0);
    for (double end = T + 40; T < end; T += 0.1) s2a_ql_away((uint64_t)(T * 1e9));
    r = feed(3, 50, 1, 0.11, 0, 1, 0); if (r < 0) r = feed(60, 16.667, 1, 0.11, 0, 1, 0);
    CHECK(r < 0 && s2a_ql_tier() == 0, "失焦 40 秒 + 回前台头 3 秒慢帧：不进窗口，之后稳 60 帧不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    fresh(); feed(20, 16.667, 1, 0.11, 0, 1, 0); r = feed(40, 50, 1, 0.11, 0, 1, 0); if (r < 0) r = feed(60, 16.667, 1, 0.11, 0, 1, 0);
    CHECK(r == 1 && s2a_ql_cpu_bound(), "负控：后台那段当局内帧喂进窗口 → 压回 30 帧且记成 CPU 跟不上（#1949 现象；实 换档 %d）", r);
    // 前台真实掉帧照常降：回前台空等 3 秒之后只跑出 30 帧 → 满一个窗口压回
    fresh(); s2a_ql_away((uint64_t)(T * 1e9)); r = feed(40, 33.333, 1, 0.9, 0, 1, &at);
    CHECK(r == 1 && at - 1000 > 32.9 && at - 1000 < 33.2, "回前台后前台真实只跑 30 帧：空等 3 秒后满 30 秒窗口照常压回（第 %.2f 秒）", at - 1000);
    // #1857 刷新率不是帧率整数倍（75 Hz 屏跑 60 帧：13.33 / 13.33 / 13.33 / 26.67 ms 循环，平均 16.67）：慢帧门槛按刷新拍取整。期望手算：
    //   门槛 60 Hz 目标 16.67 → 25.0（1.5×；1 拍 16.67 + 半拍 8.33 = 25.0，同）；75 Hz → 2 拍 26.67 + 半拍 6.67 = 33.33（> 25）；120 Hz → 2 拍 16.67 + 4.17 = 20.83 < 25 → 25；
    //   75 Hz 30 帧目标 33.33 → 3 拍 40 + 6.67 = 46.67 < 50 → 50
    { double s2a_ql_slow_us(double, double); struct { double t, v, want; } c[] = {{16666.7, 16666.7, 25000}, {16666.7, 13333.3, 33333.3}, {16666.7, 8333.3, 25000}, {33333.3, 13333.3, 50000}};
      for (unsigned i = 0; i < sizeof c / sizeof *c; i++) { double g = s2a_ql_slow_us(c[i].t, c[i].v);
        CHECK(g > c[i].want - 2 && g < c[i].want + 2, "慢帧门槛 目标 %.2f ms / 刷新一拍 %.2f ms → %.2f ms（期望 %.2f）", c[i].t / 1000, c[i].v / 1000, g / 1000, c[i].want / 1000); } }
    //   整窗：75 Hz、60 帧档按 1-1-1-2 拍出 60 帧、GPU 35%，跑 90 秒（3 个窗）：知道刷新率 → 不降；负控：不告诉刷新率（0）→ 慢帧 25% > 5% 降（#1857 现象）
    for (int known = 1; known >= 0; known--) {
        fresh(); s2a_ql_set_refresh_hz(known ? 75 : 0); r = -1;
        for (int i = 0; i < 1350 && r < 0; i++) { r = feed(0.040, 13.333, 1, 0.35, 0, 1, 0); if (r < 0) r = feed(0.02666, 26.667, 1, 0.35, 0, 1, 0); }
        if (known) CHECK(r < 0 && s2a_ql_tier() == 0, "75 Hz 屏 60 帧（13.3 / 26.7 ms 交替）、告诉了刷新率：90 秒不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
        else CHECK(r == 1, "负控：同一序列不告诉刷新率 → 压回 30 帧（#1857 现象；实 换档 %d）", r);
    }
    s2a_ql_set_refresh_hz(0);
    //   真掉帧照常降：75 Hz、每 10 帧 1 帧 46.7 ms（> 33.3）→ 降
    fresh(); s2a_ql_set_refresh_hz(75); r = -1; for (int i = 0; i < 300 && r < 0; i++) { r = feed(0.12, 13.333, 1, 0.5, 0, 1, 0); if (r < 0) r = feed(0.0467, 46.7, 1, 0.5, 0, 1, 0); }
    CHECK(r == 1, "75 Hz 屏真掉帧（每 10 帧夹 1 帧 46.7 ms）：照常压回（实 %d）", r);
    s2a_ql_set_refresh_hz(0);
    // 不跨局记：新局（setup）一律从 60 帧起
    fresh(); feed(40, 33.333, 1, 0.9, 0, 1, 0); fresh(); CHECK(s2a_ql_tier() == 0, "上一局压回 30 帧，新局：从 60 帧起（实 档 %d）", s2a_ql_tier());
    // 梯子压 / 放 60 帧时要不要告诉玩家（审计 P1-80 原因 4）：期望按「起局 / 玩家自己点的不说、没变不说、没开 60 帧 / 自动化局不说、压了说 4、放开说 0」手推
    { struct { int boot, last, hold, on, un, want; const char *why; } c[] = {
        {1, -1, 0, 1, 0, -1, "起局摆 60 帧档：不说"},
        {1, 1, 0, 1, 0, -1, "玩家点再试 60 帧放开：不说（玩家自己点的）"},
        {0, -1, 1, 1, 0, -1, "还没摆过档（last = -1）：不说"},
        {0, 0, 1, 1, 0, 4, "局中从 60 帧压回原帧率：说原因 4"},
        {0, 1, 0, 1, 0, 0, "局中按余量放开回 60 帧：说已恢复"},
        {0, 1, 1, 1, 0, -1, "压着没变：不说"},
        {0, 0, 1, 0, 0, -1, "玩家没开 60 帧：不说"},
        {0, 0, 1, 1, 1, -1, "自动化局：不说"} };
      for (unsigned i = 0; i < sizeof c / sizeof *c; i++) { int got = s2a_ql_fps_note(c[i].boot, c[i].last, c[i].hold, c[i].on, c[i].un), ok = got == c[i].want;
        bad += !ok; printf("%s 提示 %s：期望 %d → 实 %d\n", ok ? "✓" : "✗", c[i].why, c[i].want, got); } }
    printf("%s t_qladder：%d 项不符\n", bad ? "✗" : "✓", bad);
    return bad ? 1 : 0;
}
