#!/usr/bin/env python3
# 管线预建种子表（随包的 pso_manifest.tsv，nvn_mtl.m warm_worker 起局后台预建）零配置生成：给只有 game.tsv 的配置档用（维护过的配置档原样不动）。
#   python3 pso_seed.py <输出 pso_manifest.tsv> <keys.tsv> <shader_map.tsv> <R 行字节数> [来源 pso_user.tsv / 目录…]
# 管线键（pso_skey：渲染目标格式、顶点布局、混合）只能从真跑得到，离线着色器集推不出；猜错状态只省 35–55% 的建管线时间，对上才省 99%（10-25 马车8 实测）。
# 所以这是现编回收（WP14 R1，docs/研究/现编回收方案.md）的一部分：设备上玩过的管线（Documents/wire/<程序号>/pso_user.tsv）下次出包自动并进包里。
#   玩家那边由 rt_collect.py pull 连同兜底现编目录一起拉回；我们的测试局是同一机制的第一个用户：Mac 局写在本机家目录，测试设备局由 tools/dev_run.sh 收局拉回
#   ~/.s2arm/run/s2arm/pso_seed/<程序号>/。仓库里不提交按款种子。新游戏头一回在设备上跑时表是空的：那一局的首遇靠链接桩，种子表只是加速。
#   按来源先后、各自行序（= 首用序）合并去重，不排序。
# 只收对得上本次库的行：S / C 的键、R 行里顶点 / 片元的键都要在 keys.tsv 里（别的游戏版本的键不进），R 行长度要等于当前 pso_skey 的两倍（结构改过的旧行不进）。
# 只收真跑见过的（11-02 起不再补库里的计算着色器）：库里绝大多数计算着色器根本用不到——怪猎库里 6232 个、9 份真跑记录只用 33–52 个；
#   全补进来预热要编 6663 条（别款 250–970 条），测试设备1 冷首启首帧等了 64 秒、机子烤到热状态严重。玩家拿到的永远是冷包，我们没跑过的款在玩家手里
#   正好没有来源，补全照样是几千条。所以没有来源时种子表是空的：首帧不等，用到再编（首遇现编），编过的记进本机 pso_user.tsv 与管线存档，下次起局取。
import os, sys

HEAD = ('# Prewarm seed list (shipped in the app, next to shader_map.tsv). Rows: S<TAB>shader key<TAB>stage / R<TAB>render pipeline key (pso_skey hex) / C<TAB>compute shader key.\n'
        '# Generated by graphics/tools/direct/pso_seed.py: pipelines seen in real runs (pso_user.tsv), first-use order (nothing else: the rest compiles at its first use). Row order = first-use order; do not sort.\n')

def files(srcs):
    for s in srcs:
        if os.path.isdir(s): yield from (os.path.join(s, f) for f in sorted(os.listdir(s)) if f.endswith('.tsv'))
        elif os.path.isfile(s): yield s

def main(out, keys_tsv, shmap, skey_bytes, srcs):   # shmap 留在参数里（direct_lib.sh 调用口径不变），不再读
    keys = {l.strip() for l in open(keys_tsv) if l.strip()}
    # 只核「键是本包库里的」（前 16 位在 keys.tsv：别的游戏版本的键不进）；库名后缀（_b / 几何模拟的 _bgv、_bg<i> 等）合不合法只由宿主库加载器一处判
    #   （nvn_mtl.m lp_kind_of，预热 warm_stale 用同一个函数），这里不另抄后缀表。11-05 Switch Sports：原先写死只收 _b，菜单转场那批几何管线（R 行顶点键 _bgv、
    #   S 行 _bgv / _bg3）出包时整批滤掉，每局都在提交线程现建
    ok_key = lambda k: len(k) > 17 and k[16] == '_' and k[:16] in keys
    def r_keys(h):   # pso_skey 开头两段：char vs[24], fs[24]（以 0 结尾的键名）
        b = bytes.fromhex(h); return [x.split(b'\0', 1)[0].decode('ascii', 'replace') for x in (b[:24], b[24:48])]
    rows, seen, stat = [], set(), []
    for f in files(srcs):
        n = kept = 0
        for l in open(f, encoding='utf-8', errors='replace'):
            l = l.rstrip('\n'); c = l.split('\t')
            if not l or l.startswith('#'): continue
            n += 1
            if c[0] == 'S' and len(c) >= 3: good = ok_key(c[1])
            elif c[0] == 'C' and len(c) >= 2: good = ok_key(c[1])
            elif c[0] == 'R' and len(c) >= 2 and len(c[1]) == 2 * skey_bytes and all(ch in '0123456789abcdef' for ch in c[1]):
                vs, fs = r_keys(c[1]); good = ok_key(vs) and (not fs or ok_key(fs))
            elif c[0] == 'M' and len(c) >= 4 and len(c[1]) == 2 * skey_bytes and all(ch in '0123456789abcdef' for ch in c[1]):
                # 任务 / 网格管线（nvn_geometry.inc mtk_record，11-13 0400486024DEC000 开局发白根修）：顶点位置是网格键、第 2 列任务键（「-」= 无）、第 3 列补齐掩码；三个键都要是本包库的
                ms, fs = r_keys(c[1]); good = ok_key(ms) and (not fs or ok_key(fs)) and (c[2] == '-' or ok_key(c[2]))
            else: good = False
            if good and l not in seen: seen.add(l); rows.append(l); kept += 1
        stat.append((f, n, kept))
    # 只装库的行挪到末尾（11-07 卡顿线，异度3 冷装读档）：顶点 / 片元的 S 行只装载着色器库、不建管线；键不在任何 R 行里的（Mac 累积来源 4874 行，多为 10-27 前
    #   「预取即记」的老行），加载页 30 秒里占掉约四成工时（S 约 11 ms / 行、R 约 47 ms / 行，按两段吞吐联立估），把进场景要等的 R 行挤到放行之后。
    #   不删：挪到所有别的行之后，照样在后台装。几何等别的阶段的 S 行（几何管线不记 R 行，只能靠 S 行预装）与 C 行不动
    used = {k for r in rows if r.startswith(('R\t', 'M\t')) for k in r_keys(r.split('\t')[1]) if k}
    lib_only = lambda r: r.startswith('S\t') and r.split('\t')[2] in ('0', '1') and r.split('\t')[1] not in used
    deferred = [r for r in rows if lib_only(r)]
    rows = [r for r in rows if not lib_only(r)] + deferred
    tmp = out + '.tmp'
    with open(tmp, 'w', encoding='utf-8', newline='\n') as fh: fh.write(HEAD + ''.join(r + '\n' for r in rows))
    os.replace(tmp, out)
    cnt = {k: sum(1 for r in rows if r.startswith(k + '\t')) for k in 'SRCM'}
    print(f'管线种子表：S {cnt["S"]} / R {cnt["R"]} / C {cnt["C"]} / M {cnt["M"]}（只收真跑见过的；只装库的 S 行 {len(deferred)} 挪到末尾）；来源 {len(stat)} 份：'
          + '；'.join(f'{f} {k}/{n} 行可用' for f, n, k in stat) if rows else
          '管线种子表：空（没有真跑来源：首帧不等，用到再编）')

if __name__ == '__main__':
    if len(sys.argv) < 5: sys.exit(__doc__ or 'usage: pso_seed.py <out> <keys.tsv> <shader_map.tsv> <R 行字节数> [来源…]')
    main(sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]), sys.argv[5:])
